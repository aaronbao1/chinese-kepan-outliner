"""E01 read-out: tier 1 (chapter floor) vs tier 1 + tier 2 (explicit parser), scored by the repo scorer.

Input : the CBETA XML under data/raw/cbeta/ (T34n1718, T34n1723, T09n0262); the golds of
        data/eval-sets.json (sdp-T1718-zhiyi-wenju: eval-only, under data/raw/; kuiji-xuanzan: draft).
Output: experiments/E01-explicit-recovery/runs/<arm>-<set>/ (outline builds; gitignored),
        experiments/E01-explicit-recovery/metrics.json (aggregate numbers only),
        experiments/E01-explicit-recovery/SUMMARY.md (tables), and one entry per validation look in
        looks.json. Nothing here prints or writes a gold heading.

Sets (README "Method"): T1718 dev (development), T1723 dev (development; draft gold, no headline), and
with --validation the T1718 validation split (the pre-registered read-out; each run is a logged look).
The test splits are not scored here (plan M7: once, after the freeze, with --frozen).

Run: cd pipeline && .venv/bin/python ../experiments/E01-explicit-recovery/run_e01.py [--validation]
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import sys
from pathlib import Path

from chinese_workflow.common import jsonio, outline_doc
from chinese_workflow.common.splits import SplitGuard
from chinese_workflow.eval.score import score
from chinese_workflow.outline.pipeline import OutlineConfig, build

HERE = Path(__file__).resolve().parent
KUIJI_LEVEL1 = [
    {"heading_src": "序分", "from_pin": "序品", "to_pin": "序品", "source": "R03 F22"},
    {"heading_src": "正宗", "from_pin": "方便品", "to_pin": "授學無學人記品", "source": "R03 F22"},
    {"heading_src": "流通", "from_pin": "法師品", "to_pin": "普賢菩薩勸發品", "source": "R03 F22"},
]
SETS = {
    "T1718-dev": dict(commentary="T34n1718", scheme_id="zhiyi-wenju", span="dev", level1=[],
                      gold="sdp-T1718-zhiyi-wenju", split="dev"),
    "T1723-dev": dict(commentary="T34n1723", scheme_id="kuiji-xuanzan", span="dev",
                      level1=KUIJI_LEVEL1, gold="kuiji-xuanzan", split="dev"),
    "T1718-validation": dict(commentary="T34n1718", scheme_id="zhiyi-wenju", span="validation",
                             level1=[], gold="sdp-T1718-zhiyi-wenju", split="validation"),
}
ARMS = ("tier1", "tier2")


def _row(m: dict) -> dict:
    """The aggregate parts of one metrics dict (chinese_workflow.eval.score) that SUMMARY.md shows."""
    t0 = m["rows"].get("t=0", {})
    t1 = m["rows"].get("t=1", {})
    return {
        "s_f1": m.get("s_f1"),
        "f_f1": m.get("f_f1"),
        "s_f1_t1": t1.get("s_f1") if t1.get("available") else None,
        "locator_only": t0.get("locator_only"),
        "per_depth": t0.get("per_depth"),
        "child_count": m.get("child_count"),
        "counts": {side: {k: v for k, v in c.items() if k in ("nodes", "counted")}
                   for side, c in m["counts"].items()},
        "disclosures": {k: m["disclosures"].get(k) for k in ("gold_status", "seeded_by", "headline",
                                                             "split", "t", "key")},
    }


def run_set(name: str, spec: dict, arm: str) -> dict:
    cfg = OutlineConfig(mode="sutra", root="T09n0262", commentary=spec["commentary"],
                        scheme_id=spec["scheme_id"], span=spec["span"], source=arm,
                        target_role="commentary", level1=spec["level1"])
    out = HERE / "runs" / ("%s-%s" % (arm, name))
    res = build(cfg, out, guard=SplitGuard())
    metrics = score(res["doc"], spec["gold"], split=spec["split"])
    row = _row(metrics)
    row["nodes_predicted"] = res["doc"]["metadata"]["node_count"]
    row["rejected_doctrinal_lists"] = len(((res["report"].get("tier2") or {}).get("rejected")) or [])
    return row


def fmt(x) -> str:
    return "—" if x is None else ("%.3f" % x if isinstance(x, float) else str(x))


def summary_md(results: dict, commit: dict) -> str:
    lines = [
        "# E01 SUMMARY",
        "",
        "Generated by `run_e01.py` on %s at pipeline commit `%s`%s. Aggregate numbers only."
        % (dt.date.today().isoformat(), (commit["commit"] or "?")[:12],
           " (dirty)" if commit["dirty"] else ""),
        "Key `commentary.explained`; S-F1 = node F1 over (explained line, depth, parent path);",
        "locator-only = explained line alone (detection without attachment).",
        "",
        "| Set | Arm | S-F1 t=0 (P / R / F) | S-F1 t=1 F | F-F1 t=0 F | locator-only F | gold nodes in scope"
        " | predicted in scope | headline |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for name, arms in results.items():
        for arm, r in arms.items():
            s = r.get("s_f1") or {}
            lines.append("| %s | %s | %s / %s / %s | %s | %s | %s | %s | %s | %s |" % (
                name, arm, fmt(s.get("P")), fmt(s.get("R")), fmt(s.get("F")),
                fmt((r.get("s_f1_t1") or {}).get("F")), fmt((r.get("f_f1") or {}).get("F")),
                fmt((r.get("locator_only") or {}).get("F")),
                fmt(r["counts"]["gold"].get("counted")), fmt(r["counts"]["pred"].get("counted")),
                fmt(r["disclosures"].get("headline"))))
    lines += ["", "Per-depth rows and all counts: `metrics.json`."]
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--validation", action="store_true",
                    help="also score the T1718 validation split (logged as a look)")
    args = ap.parse_args(argv)
    names = ["T1718-dev", "T1723-dev"] + (["T1718-validation"] if args.validation else [])
    results = {name: {arm: run_set(name, SETS[name], arm) for arm in ARMS} for name in names}
    commit = outline_doc.pipeline_commit()
    jsonio.write_json({"commit": commit, "results": results}, HERE / "metrics.json")
    (HERE / "SUMMARY.md").write_text(summary_md(results, commit), encoding="utf-8")
    if args.validation:
        looks = jsonio.read_json(HERE / "looks.json")
        looks["looks"].append({"date": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
                               "split": "validation", "set": "T1718-validation", "commit": commit,
                               "arms": list(ARMS)})
        jsonio.write_json(looks, HERE / "looks.json")
    json.dump({n: {a: (r.get("s_f1") or {}).get("F") for a, r in arms.items()}
               for n, arms in results.items()}, sys.stdout, indent=1)
    print()
    return 0


if __name__ == "__main__":
    sys.exit(main())
